"""Run every case in cases.json through the app's finder and write results.md.

Needs Neo4j running.   python test_data/run_cases.py
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path[:0] = [str(HERE.parent), str(HERE.parent / "pipeline"), str(HERE.parent / "webapp")]

from neo4j import GraphDatabase  # noqa: E402

import finder  # noqa: E402
from settings import connection  # noqa: E402
from text_synonyms import Lexicon  # noqa: E402


def verdict(expected, occurrence):
    answer = occurrence["answer"]
    if not answer:
        return "no synonym", "-", "-"
    got = answer["name"]
    if expected not in got.split(", "):
        result = "wrong meaning"
    elif occurrence["certain"]:
        result = "correct"
    else:
        result = "correct by fallback (context undecided)"
    return result, got, answer["best"]["word"]


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    cases = json.loads((HERE / "cases.json").read_text(encoding="utf-8"))
    uri, auth, database = connection()
    rows, tally = [], {}
    with GraphDatabase.driver(uri, auth=auth) as driver, driver.session(database=database) as session:
        lex = Lexicon(session)
        for c in cases:
            data = finder.find(session, lex, c["text"], c["word"])
            if data["status"] != "ok":
                rows.append((c, 1, "explained: " + data["title"], "-", "-"))
                tally["explained"] = tally.get("explained", 0) + 1
                continue
            expected = c.get("expected_per_occurrence", [c["expected_meaning"]])
            for n, (want, occ) in enumerate(zip(expected, data["occurrences"]), 1):
                result, got, best = verdict(want, occ)
                rows.append((c, n, result, got, best))
                tally[result] = tally.get(result, 0) + 1

    lines = ["# Test results", "", "Generated by `test_data/run_cases.py`.", "",
             "| Outcome | Count |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in sorted(tally.items(), key=lambda kv: -kv[1])]
    lines += ["", "| Case | Word | Expected meaning | App's meaning | Best synonym | Outcome |", "|---|---|---|---|---|---|"]
    for c, n, result, got, best in rows:
        want = c.get("expected_per_occurrence", [c["expected_meaning"]])[n - 1]
        case_id = c["id"] + (f" ({n})" if "expected_per_occurrence" in c else "")
        lines.append(f"| {case_id} | {c['word']} | {want} | {got} | {best} | {result} |")
    (HERE / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
