# Labels in the source that are data-entry debris, not meanings.
NOISE_LABELS = {"चपयति", "अनार्थाः", "काशृ दीप्तौ"}

_CASE_RULES = [
    (r"त्याम्$|त्यां$", "ति"), (r"ायाम्$|ायां$", "ा"), (r"ियाम्$|ियां$", "ी"),
    (r"्याम्$|्यां$", "ि"), (r"ौ$", "ि"), (r"े$", ""),
]


def clean(text: str) -> str:
    """Normalise whitespace, zero-width characters and the OCR avagraha."""
    text = re.sub(r"[‌‍﻿]", "", str(text)).replace("ƒ", "ऽ")
    return re.sub(r"\s+", " ", text).strip()


def lemma(word: str) -> str:
    """Reduce an inflected sense word to its Sense lemma."""
    word = clean(word).strip("।.,")
    word = re.sub(r"ञ्च$", "ं", word)  # हिंसायाञ्च -> हिंसायां (…+ च)
    if word in IRREGULAR:
        return ALIASES.get(IRREGULAR[word], IRREGULAR[word])
    for pattern, stem_end in _CASE_RULES:
        if re.search(pattern, word):
            word = re.sub(pattern, stem_end, word)
            break
    return ALIASES.get(word, word)
